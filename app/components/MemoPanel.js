function renderMemo(text) {
    if (!text) return null;
    const paragraphs = text.split(/\n\s*\n/);
    return paragraphs.map((para, idx) => {
      const trimmed = para.trim();
      if (!trimmed) return null;
  
      const headingMatch = trimmed.match(/^\*\*(.+?)\*\*\s*$/);
      if (headingMatch) {
        return (
          <h3
            key={idx}
            className="font-serif text-3xl italic text-[var(--accent)] mt-10 mb-4 first:mt-0"
          >
            {headingMatch[1]}
          </h3>
        );
      }
  
      const parts = trimmed.split(/(\*\*[^*]+\*\*)/g);
      return (
        <p key={idx} className="text-[15px] text-[var(--text)] leading-[1.8] mb-4">
          {parts.map((p, i) => {
            const m = p.match(/^\*\*(.+?)\*\*$/);
            if (m) return <strong key={i} className="text-[var(--accent)] font-semibold">{m[1]}</strong>;
            return <span key={i}>{p}</span>;
          })}
        </p>
      );
    });
  }
  
  export default function MemoPanel({ memo, memoError }) {
    return (
      <div className="border border-[var(--border)] bg-[var(--bg-card)] rounded-lg overflow-hidden">
        <div className="px-8 py-3 border-b border-[var(--border)] bg-[var(--bg)] flex items-center justify-between">
          <div className="font-mono text-[10px] tracking-[0.25em] uppercase text-[var(--text-faint)]">
            Investment Memo · Generated by Claude
          </div>
          <div className="flex items-center gap-2 font-mono text-[10px] tracking-widest uppercase text-[var(--text-faint)]">
            <span className="w-1.5 h-1.5 rounded-full bg-[var(--accent)]" />
            Ready
          </div>
        </div>
  
        <div className="p-10">
          {memoError ? (
            <div className="text-sm text-[var(--bad)]">Memo generation failed: {memoError}</div>
          ) : memo ? (
            <div className="max-w-3xl">{renderMemo(memo)}</div>
          ) : (
            <div className="text-sm italic text-[var(--text-faint)]">No memo generated.</div>
          )}
        </div>
      </div>
    );
  }